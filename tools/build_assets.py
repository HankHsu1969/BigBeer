"""Turn the raw Higgsfield generations in assets/raw into game-ready assets.

- crops every cut-out sprite to its alpha bounds and resizes it
- measures where each vessel's base sits (axis + base width) so the game can
  stand the sprite exactly on its physics footprint
- writes js/sprites-meta.js and the optimised images into assets/img

Usage:  python tools/build_assets.py
"""
import json
import os

import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RAW = os.path.join(ROOT, "assets", "raw")
OUT = os.path.join(ROOT, "assets", "img")
os.makedirs(OUT, exist_ok=True)


def crop_alpha(im, thresh=10, pad=4):
    a = np.array(im.getchannel("A"))
    ys, xs = np.where(a > thresh)
    x0, x1 = max(0, xs.min() - pad), min(im.width, xs.max() + 1 + pad)
    y0, y1 = max(0, ys.min() - pad), min(im.height, ys.max() + 1 + pad)
    return im.crop((x0, y0, x1, y1))


def fit(im, max_w=None, max_h=None):
    s = 1.0
    if max_w:
        s = min(s, max_w / im.width)
    if max_h:
        s = min(s, max_h / im.height)
    if s < 1.0:
        im = im.resize((round(im.width * s), round(im.height * s)), Image.LANCZOS)
    return im


def vessel_meta(im):
    a = np.array(im.getchannel("A")).astype(np.int32)
    solid = a > 128
    rows = np.where(solid.any(axis=1))[0]
    bottom = rows.max()
    band = max(3, int(im.height * 0.03))
    xs = np.where(solid[bottom - band:bottom + 1].any(axis=0))[0]
    base_l, base_r = xs.min(), xs.max()
    axis = (base_l + base_r) / 2.0
    base_half = (base_r - base_l) / 2.0
    left = np.where(solid.any(axis=0))[0].min()
    half_w = max(base_half, axis - left)
    return {
        "w": im.width,
        "h": im.height,
        "axisX": round(float(axis), 1),
        "halfW": round(float(half_w), 1),
        "baseFrac": round(float(base_half / half_w), 3),
        "bottom": int(bottom),
    }


def main():
    meta = {}
    for i in range(11):
        key = f"m{i:02d}"
        im = Image.open(os.path.join(RAW, f"{key}_nobg.png")).convert("RGBA")
        im = fit(crop_alpha(im), max_w=640, max_h=640)
        im.save(os.path.join(OUT, f"{key}.webp"), "WEBP", quality=92, method=6)
        meta[key] = vessel_meta(im)
        print(key, meta[key])

    for name, kw in (("waitress", {"max_h": 900}), ("sepp", {"max_h": 900}), ("logo", {"max_w": 1000})):
        im = Image.open(os.path.join(RAW, f"{name}_nobg.png")).convert("RGBA")
        im = fit(crop_alpha(im), **kw)
        im.save(os.path.join(OUT, f"{name}.webp"), "WEBP", quality=92, method=6)
        meta[name] = {"w": im.width, "h": im.height}
        print(name, meta[name])

    bg = Image.open(os.path.join(RAW, "bg.png")).convert("RGB")
    bg = fit(bg, max_w=2560)
    bg.save(os.path.join(OUT, "bg.jpg"), "JPEG", quality=86, optimize=True, progressive=True)
    meta["bg"] = {"w": bg.width, "h": bg.height}

    wood = Image.open(os.path.join(RAW, "wood.png")).convert("RGB")
    wood = fit(wood, max_w=1536)
    wood.save(os.path.join(OUT, "wood.jpg"), "JPEG", quality=88, optimize=True)
    meta["wood"] = {"w": wood.width, "h": wood.height}

    with open(os.path.join(ROOT, "js", "sprites-meta.js"), "w", encoding="utf-8") as f:
        f.write("// Generated by tools/build_assets.py - sprite sizes and base anchors\n")
        f.write("window.BB_SPRITES = " + json.dumps(meta, indent=1) + ";\n")


if __name__ == "__main__":
    main()
